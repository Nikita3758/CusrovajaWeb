function updateTranslations(lang) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (element.tagName === 'IMG') {
                element.alt = translations[lang][key];
            } else if (element.placeholder) {
                element.placeholder = translations[lang][key];
            } else if (element.tagName === 'OPTION') {
                element.textContent = translations[lang][key];
            } else if (element.tagName === 'SPAN') {
                element.textContent = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });
    document.documentElement.lang = lang;
    

    const isAdminPage = document.querySelector('.admin-panel');
    const isTestimonialsPage = document.querySelector('.testimonials-page');
    const isArticlesPage = document.querySelector('.articles-page');
    const isDestinationsPage = document.querySelector('.destinations-page');
    
    if (isAdminPage && translations[lang].adminPanel) {
        document.title = translations[lang].adminPanel + " | Travel";
    } else if (isTestimonialsPage && translations[lang].allTestimonials) {
        document.title = translations[lang].allTestimonials + " | Travel";
    } else if (isArticlesPage && translations[lang].travelStories) {
        document.title = translations[lang].travelStories + " | Travel";
    } else if (isDestinationsPage && translations[lang].allDestinations) {
        document.title = translations[lang].allDestinations + " | Travel";
    } else if (translations[lang].exploreTravel) {
        document.title = translations[lang].exploreTravel;
    }

    if (isAdminPage) {
        updateModalTitle(lang);
    }

    updateDynamicContent(lang);
}

function updateDynamicContent(lang) {
    const noResults = document.querySelector('.no-results');
    if (noResults && translations[lang].noDestinationsFound) {
        noResults.textContent = translations[lang].noDestinationsFound;
    }

    const exploreButtons = document.querySelectorAll('.explore-btn');
    exploreButtons.forEach(btn => {
        if (translations[lang].explore) {
            btn.textContent = translations[lang].explore;
        }
    });

    const locationLabels = document.querySelectorAll('.location-label');
    locationLabels.forEach(el => {
        if (translations[lang].location) {
            el.textContent = translations[lang].location + ':';
        }
    });
    
    const categoryLabels = document.querySelectorAll('.category-label');
    categoryLabels.forEach(el => {
        if (translations[lang].category) {
            el.textContent = translations[lang].category + ':';
        }
    });
    
    const ratingLabels = document.querySelectorAll('.rating-label');
    ratingLabels.forEach(el => {
        if (translations[lang].rating) {
            el.textContent = translations[lang].rating + ':';
        }
    });

    const paginationButtons = document.querySelectorAll('.pagination-btn');
    paginationButtons.forEach(btn => {
        if (btn.textContent.includes('Load More') && translations[lang].loadMore) {
            btn.textContent = translations[lang].loadMore;
        }
    });

    const pageInfo = document.querySelector('.page-info');
    if (pageInfo && translations[lang].page && translations[lang].of) {
        const matches = pageInfo.textContent.match(/(\d+)\s+of\s+(\d+)/);
        if (matches) {
            pageInfo.textContent = `${translations[lang].page} ${matches[1]} ${translations[lang].of} ${matches[2]}`;
        }
    }
}

function updateModalTitle(lang) {
    const modalTitle = document.getElementById('modalTitle');
    const currentTabElement = document.getElementById('currentTab');
    const editIdElement = document.getElementById('editId');

    if (!modalTitle || !currentTabElement || !editIdElement) {
        return; 
    }
    
    const currentTab = currentTabElement.value;
    const isEditMode = editIdElement.value !== '';
    
    if (translations[lang]) {
        if (isEditMode) {
            switch(currentTab) {
                case 'destinations':
                    modalTitle.textContent = translations[lang].editDestination;
                    break;
                case 'testimonials':
                    modalTitle.textContent = translations[lang].editTestimonial;
                    break;
                case 'articles':
                    modalTitle.textContent = translations[lang].editArticle;
                    break;
            }
        } else {
            switch(currentTab) {
                case 'destinations':
                    modalTitle.textContent = translations[lang].addNewDestination;
                    break;
                case 'testimonials':
                    modalTitle.textContent = translations[lang].addNewTestimonial;
                    break;
                case 'articles':
                    modalTitle.textContent = translations[lang].addNewArticle;
                    break;
            }
        }
    }
}
        
document.addEventListener('DOMContentLoaded', function() {
    const savedLang = localStorage.getItem('language') || 'en';
    updateTranslations(savedLang);

    const languageSelect = document.getElementById('language-select');
    if (languageSelect) {
        languageSelect.value = savedLang;
        languageSelect.addEventListener('change', function() {
            const lang = this.value;
            localStorage.setItem('language', lang);
            updateTranslations(lang);
        });
    }
});